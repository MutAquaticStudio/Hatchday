export function viError(err: unknown): string {
  const e = err as { code?: string; message?: string; status?: number } | null;
  if (!e) return _t('Có lỗi xảy ra. Bạn thử lại nhé.');
  if (e.code && AUTH[e.code]) return AUTH[e.code];
  const m = e.message || '';
  if (/captcha_(failed|timeout|load)/.test(m)) return AUTH.captcha_failed;
  for (const k of Object.keys(RPC)) if (m.includes(k)) return RPC[k];
  if (e.status === 0 || /fetch|network/i.test(m)) return _t('Không kết nối được máy chủ. Bạn kiểm tra mạng rồi thử lại nhé.');
  return _t('Có lỗi xảy ra. Bạn thử lại nhé.');
}
